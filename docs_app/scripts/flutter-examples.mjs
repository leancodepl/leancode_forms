/**
 * Turns the Dart fences inside `<AdvancedFormsExample>` elements in ../docs
 * into a compilable Flutter package, then into one web bundle the docs site
 * serves.
 *
 *   generate  write flutter/lib/generated/** + web/examples.json + the manifest
 *   check     fail if the committed manifest no longer matches the MDX
 *   build     generate, then `flutter build web` into public/flutter-examples
 *
 * The ids come from lib/flutter-examples/extract.mjs, the same module the remark
 * plugin uses, so what a page asks for is what the bundle contains.
 */
import { spawn } from "node:child_process"
import { existsSync } from "node:fs"
import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises"
import { dirname, join, relative, resolve } from "node:path"
import { fileURLToPath } from "node:url"
import remarkMdx from "remark-mdx"
import remarkParse from "remark-parse"
import { unified } from "unified"
import { collectExamples, exampleTag } from "../lib/flutter-examples/extract.mjs"

const docsApp = resolve(fileURLToPath(new URL(".", import.meta.url)), "..")
const repoRoot = resolve(docsApp, "..")
const docsDir = join(repoRoot, "docs")
const flutterDir = join(docsApp, "flutter")
const generatedDir = join(flutterDir, "lib", "generated")
const galleryFile = join(flutterDir, "web", "examples.json")
const bundleDir = join(docsApp, "public", "flutter-examples")
const manifestFile = join(docsApp, "lib", "flutter-examples", "manifest.generated.ts")

const parser = unified().use(remarkParse).use(remarkMdx)

/** Every `.mdx` under ../docs, relative to it, in a stable order. */
async function docFiles(dir = docsDir, prefix = "") {
  const entries = await readdir(dir, { withFileTypes: true })
  const files = []
  for (const entry of entries.toSorted((a, b) => a.name.localeCompare(b.name))) {
    const rel = prefix ? `${prefix}/${entry.name}` : entry.name
    if (entry.isDirectory()) files.push(...(await docFiles(join(dir, entry.name), rel)))
    else if (entry.name.endsWith(".mdx")) files.push(rel)
  }
  return files
}

async function readExamples() {
  const examples = new Map()
  const problems = []

  for (const doc of await docFiles()) {
    const source = await readFile(join(docsDir, doc), "utf8")
    if (!source.includes(exampleTag)) continue

    for (const { example } of collectExamples(parser.parse(source))) {
      if (example.dart === "") {
        problems.push(`${doc}: <${exampleTag}> has no \`\`\`dart fence`)
        continue
      }
      if (!example.preview) {
        problems.push(
          `${doc}: <${exampleTag}> has no widget to mount — add preview="SomeWidget" ` +
            "or declare a class extending StatelessWidget/StatefulWidget",
        )
        continue
      }

      // Identical snippets on two pages hash the same and share one compiled
      // example; that is a feature, not a clash.
      const existing = examples.get(example.id)
      if (existing) existing.docs.push(doc)
      else examples.set(example.id, { ...example, docs: [doc] })
    }
  }

  if (problems.length > 0) {
    throw new Error(`Cannot build the docs examples:\n${problems.map(p => `  - ${p}`).join("\n")}`)
  }
  return [...examples.values()].toSorted((a, b) => a.id.localeCompare(b.id))
}

const banner = source =>
  `// GENERATED by docs_app/scripts/flutter-examples.mjs from ${source}.\n` +
  "// Edit the snippet in the MDX file; this file is overwritten.\n"

function dartLibrary(example) {
  return (
    banner(`docs/${example.docs.join(", docs/")}`) +
    // The prelude is ours, not the author's: a snippet that happens not to need
    // one of these should not have to carry a lint about it.
    "// ignore_for_file: unused_import\n" +
    "\n" +
    "import 'package:advanced_forms/advanced_forms.dart';\n" +
    "import 'package:advanced_forms_docs_islands/support/support.dart';\n" +
    "import 'package:flutter/material.dart';\n" +
    "\n" +
    `${example.dart}\n` +
    // Targeted rather than file-wide, so the snippet above stays fully linted.
    "// Whether the preview has a const constructor is the snippet's business.\n" +
    "// ignore: prefer_const_constructors\n" +
    `Widget buildExample(BuildContext context) => ${example.preview}();\n`
  )
}

function dartRegistry(examples) {
  const imports = examples.map(e => `import 'example_${e.id}.dart' as example_${e.id};`).join("\n")
  const entries = examples.map(e => `  '${e.id}': example_${e.id}.buildExample,`).join("\n")

  return (
    banner("the docs") +
    "\n" +
    "import 'package:flutter/widgets.dart';\n" +
    (imports ? `\n${imports}\n` : "") +
    "\n" +
    "/// Every example in this bundle, keyed by the content hash of its Dart\n" +
    "/// source. `main.dart` looks up the id the host page passed to `addView`.\n" +
    (entries
      ? `final Map<String, WidgetBuilder> examples = {\n${entries}\n};\n`
      : "final Map<String, WidgetBuilder> examples = {};\n")
  )
}

function manifest(examples) {
  const entries = examples
    .map(
      e =>
        `  "${e.id}": { preview: ${JSON.stringify(e.preview)}, docs: ${JSON.stringify(e.docs)}` +
        (e.helpers.length > 0 ? `, helpers: ${JSON.stringify(e.helpers)}` : "") +
        " },",
    )
    .join("\n")

  return (
    "/*\n * AI-Provenance:\n *   model: Claude Opus 5\n *   harness: Cursor\n */\n" +
    "// GENERATED by scripts/flutter-examples.mjs — run `npm run examples:generate`.\n" +
    "//\n" +
    "// Committed so that `next build` can tell a stale bundle from a fresh one\n" +
    "// without having the Flutter SDK available. `npm run examples:check` fails\n" +
    "// the build when this drifts from the MDX.\n" +
    "\n" +
    "export interface FlutterExample {\n" +
    "  /** The widget the island mounts. */\n" +
    "  preview: string\n" +
    "  /** Pages the snippet appears on, for error messages. */\n" +
    "  docs: string[]\n" +
    "  /** Docs-only `Docs*` widgets the snippet uses, if any. */\n" +
    "  helpers?: string[]\n" +
    "}\n" +
    "\n" +
    (entries
      ? `export const flutterExamples: Record<string, FlutterExample> = {\n${entries}\n}\n`
      : "export const flutterExamples: Record<string, FlutterExample> = {}\n")
  )
}

async function writeIfChanged(file, content) {
  const previous = existsSync(file) ? await readFile(file, "utf8") : null
  if (previous === content) return false
  await mkdir(dirname(file), { recursive: true })
  await writeFile(file, content)
  return true
}

async function generate({ quiet = false } = {}) {
  const examples = await readExamples()

  await rm(generatedDir, { recursive: true, force: true })
  await mkdir(generatedDir, { recursive: true })
  for (const example of examples) {
    await writeFile(join(generatedDir, `example_${example.id}.dart`), dartLibrary(example))
  }
  await writeFile(join(generatedDir, "registry.dart"), dartRegistry(examples))

  await writeIfChanged(
    galleryFile,
    JSON.stringify(
      examples.map(e => ({ id: e.id, preview: e.preview, docs: e.docs })),
      null,
      2,
    ) + "\n",
  )
  const manifestChanged = await writeIfChanged(manifestFile, manifest(examples))

  if (!quiet) {
    console.log(
      `${examples.length} example${examples.length === 1 ? "" : "s"} from ` +
        `${new Set(examples.flatMap(e => e.docs)).size} page(s)` +
        (manifestChanged ? " (manifest updated)" : ""),
    )
  }
  return examples
}

async function check() {
  const examples = await readExamples()
  const expected = manifest(examples)
  const actual = existsSync(manifestFile) ? await readFile(manifestFile, "utf8") : ""

  if (expected === actual) {
    console.log(`manifest is up to date (${examples.length} example(s))`)
    return
  }

  const idsIn = text => new Set([...text.matchAll(/^ {2}"([0-9a-f]{12})":/gm)].map(m => m[1]))
  const before = idsIn(actual)
  const after = idsIn(expected)
  const added = [...after].filter(id => !before.has(id))
  const removed = [...before].filter(id => !after.has(id))

  throw new Error(
    "lib/flutter-examples/manifest.generated.ts is out of date — run `npm run examples:generate`.\n" +
      (added.length ? `  new examples:     ${added.join(", ")}\n` : "") +
      (removed.length ? `  gone examples:    ${removed.join(", ")}\n` : "") +
      (!added.length && !removed.length ? "  metadata changed (preview or page list)\n" : ""),
  )
}

const run = (command, args, cwd) =>
  new Promise((resolvePromise, reject) => {
    const child = spawn(command, args, { cwd, stdio: "inherit" })
    child.on("error", reject)
    child.on("exit", code => (code === 0 ? resolvePromise() : reject(new Error(`${command} exited with ${code}`))))
  })

/**
 * Deletes what this build can never request. `flutter build web` populates
 * `canvaskit/` with every renderer and variant it knows about — the Chromium-
 * only CanvasKit, the Wasm renderer, symbol files for a crash reporter — which
 * is ~24 MB of the output. This build is dart2js + CanvasKit and the bootstrap
 * pins `canvasKitVariant: "full"`, so exactly two of those files are reachable.
 *
 * Written as an allowlist so a future SDK adding more variants does not quietly
 * start deploying them. The service worker goes too: nothing registers one.
 */
async function pruneBundle() {
  const keep = new Set(["canvaskit.js", "canvaskit.wasm"])
  for (const entry of await readdir(join(bundleDir, "canvaskit"), { withFileTypes: true })) {
    if (keep.has(entry.name)) continue
    await rm(join(bundleDir, "canvaskit", entry.name), { recursive: true, force: true })
  }
  await rm(join(bundleDir, "flutter_service_worker.js"), { force: true })
}

async function build() {
  const examples = await generate()
  if (examples.length === 0) {
    console.log("no examples in the docs — skipping the Flutter build")
    await rm(bundleDir, { recursive: true, force: true })
    return
  }
  // `--no-web-resources-cdn` self-hosts CanvasKit instead of fetching it from
  // gstatic. It is the same ~1.6 MB over the wire, but same-origin: the docs
  // work offline, in regions that block gstatic, and without a third-party
  // request on every page that has an example.
  await run(
    "flutter",
    ["build", "web", "--release", "--no-web-resources-cdn", "-o", relative(flutterDir, bundleDir)],
    flutterDir,
  )
  await pruneBundle()
}

async function watch() {
  await generate()
  console.log(`watching ${relative(repoRoot, docsDir)} for changes`)

  const { watch: watchFs } = await import("node:fs")
  let queued = null
  watchFs(docsDir, { recursive: true }, (_, file) => {
    if (file && !file.endsWith(".mdx")) return
    clearTimeout(queued)
    queued = setTimeout(() => {
      generate().catch(error => console.error(String(error.message ?? error)))
    }, 150)
  })
}

const args = process.argv.slice(2)
const modes = { generate, check, build, watch }
const mode = args.includes("--watch") ? "watch" : args[0]

if (!(mode in modes)) {
  console.error(`usage: flutter-examples.mjs <${Object.keys(modes).join("|")}> [--watch]`)
  process.exit(2)
}

try {
  await modes[mode]()
} catch (error) {
  console.error(String(error?.message ?? error))
  process.exit(1)
}
